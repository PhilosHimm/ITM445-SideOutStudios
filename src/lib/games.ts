export function getGame(slug: string): Game | undefined {
  return games.find((g) => g.slug === slug);
}

export function getPrevNext(slug: string): { prev: Game | null; next: Game | null } {
  const game = games.find((g) => g.slug === slug);
  if (!game) return { prev: null, next: null };
  const playerGames = games.filter((g) => g.player === game.player);
  const idx = playerGames.findIndex((g) => g.slug === slug);
  return {
    prev: idx > 0 ? playerGames[idx - 1] : null,
    next: idx < playerGames.length - 1 ? playerGames[idx + 1] : null,
  };
}
